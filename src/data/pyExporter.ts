import { SpectrumData } from '../types';

export function generatePythonTkinterCode(dataset: SpectrumData): string {
  // Extract points for hardcoding as interactive default data
  const xVals = dataset.x_orig.map(v => v.toFixed(4)).join(', ');
  const yVals = dataset.y_orig.map(v => v.toFixed(6)).join(', ');

  return `#!/usr/bin/env python3
\"\"\"
Labscribber Standalone Python Spectroscopy Workstation GUI
Generated by Labscribber
\"\"\"

import tkinter as tk
from tkinter import ttk, filedialog, messagebox
import numpy as np
import matplotlib
matplotlib.use('TkAgg')
import matplotlib.pyplot as plt
from matplotlib.backends.backend_tkagg import FigureCanvasTkAgg, NavigationToolbar2Tk

class LabscriberGUI:
    def __init__(self, root):
        self.root = root
        self.root.title("Labscribber Standalone Spectroscopy GUI")
        self.root.geometry("1100x750")
        self.root.configure(bg="#0f172a") # Slate-900 background

        # Initial default data embedded from active session
        self.x_orig = np.array([${xVals}])
        self.y_orig = np.array([${yVals}])
        
        self.x = np.copy(self.x_orig)
        self.y_processed = np.copy(self.y_orig)
        self.peaks = []
        self.smoothing_win = 11
        self.normalize_active = False
        
        # Configure overall themes
        self.style = ttk.Style()
        self.style.theme_use('clam')
        self.style.configure('.', background='#1e293b', foreground='#f1f5f9', font=('Inter', 10))
        self.style.configure('TFrame', background='#0f172a')
        self.style.configure('TLabel', background='#1e293b', foreground='#f1f5f9')
        self.style.configure('TabFrame.TFrame', background='#1e293b')
        self.style.configure('TButton', background='#0f766e', foreground='#ffffff', font=('Inter', 9, 'bold'))
        self.style.map('TButton', background=[('active', '#0d9488')])
        self.style.configure('Danger.TButton', background='#be123c', foreground='#ffffff')
        self.style.map('Danger.TButton', background=[('active', '#e11d48')])
        
        # Create Main Split Panels
        self.main_container = ttk.Frame(root)
        self.main_container.pack(fill=tk.BOTH, expand=True, padx=10, pady=10)

        # Left panel (Controls)
        self.ctrl_panel = ttk.Frame(self.main_container, width=320)
        self.ctrl_panel.pack(side=tk.LEFT, fill=tk.Y, padx=(0, 10))
        self.ctrl_panel.pack_propagate(False)

        # Right panel (Plot Area)
        self.plot_panel = ttk.Frame(self.main_container)
        self.plot_panel.pack(side=tk.RIGHT, fill=tk.BOTH, expand=True)

        self.setup_control_widgets()
        self.setup_plot_area()
        self.update_plot()

    def setup_control_widgets(self):
        # Header banner
        hdr = tk.Label(self.ctrl_panel, text="LABSCRIBBER DESKTOP", bg="#0d9488", fg="white", font=("Inter", 12, "bold"), pady=8)
        hdr.pack(fill=tk.X, pady=(0, 10))

        # File I/O Frame
        f_io = ttk.LabelFrame(self.ctrl_panel, text=" Data Input Stream ")
        f_io.pack(fill=tk.X, padx=10, pady=5)
        
        lbl_info = ttk.Label(f_io, text="Active source: ${dataset.name}", font=("Inter", 8, "italic"), justify=tk.LEFT)
        lbl_info.pack(fill=tk.Y, padx=5, pady=5)

        btn_load = ttk.Button(f_io, text="Load local CSV Coordinate File", command=self.load_csv)
        btn_load.pack(fill=tk.X, padx=10, pady=8)

        # Signal Processing Frame
        f_proc = ttk.LabelFrame(self.ctrl_panel, text=" Pre-processing Operations ")
        f_proc.pack(fill=tk.X, padx=10, pady=5)

        # Normalization toggle
        self.norm_var = tk.BooleanVar(value=False)
        chk_norm = ttk.Checkbutton(f_proc, text="Enable Min/Max Normalization", variable=self.norm_var, command=self.apply_preprocessing)
        chk_norm.pack(anchor=tk.W, padx=10, pady=5)

        # Smoothing control selector
        lbl_smooth = ttk.Label(f_proc, text="Moving Windows Smoothing:")
        lbl_smooth.pack(anchor=tk.W, padx=10, pady=2)
        
        self.smooth_scale = tk.Scale(f_proc, from_=3, to=51, orient=tk.HORIZONTAL, resolution=2, bg="#1e293b", fg="white", highlightthickness=0)
        self.smooth_scale.set(11)
        self.smooth_scale.pack(fill=tk.X, padx=10, pady=5)
        
        btn_smooth = ttk.Button(f_proc, text="Apply Moving Average", command=self.apply_preprocessing)
        btn_smooth.pack(fill=tk.X, padx=10, pady=8)

        # Peak Finding Frame
        f_peaks = ttk.LabelFrame(self.ctrl_panel, text=" Advanced Spectroscopy Peaks ")
        f_peaks.pack(fill=tk.X, padx=10, pady=5)

        lbl_prom = ttk.Label(f_peaks, text="Peak prominence threshold (Y):")
        lbl_prom.pack(anchor=tk.W, padx=10, pady=2)

        self.prom_entry = ttk.Entry(f_peaks)
        self.prom_entry.insert(0, "0.05")
        self.prom_entry.pack(fill=tk.X, padx=10, pady=5)

        btn_peaks = ttk.Button(f_peaks, text="Auto Detect Coordinates", command=self.auto_pick_peaks)
        btn_peaks.pack(fill=tk.X, padx=10, pady=8)

        # State Reset Buttons
        f_reset = ttk.Frame(self.ctrl_panel)
        f_reset.pack(fill=tk.X, padx=10, pady=15)
        
        btn_rst = ttk.Button(f_reset, text="Reset Raw Data Streams", style="Danger.TButton", command=self.reset_data)
        btn_rst.pack(fill=tk.X, pady=5)

        logo = tk.Label(self.ctrl_panel, text="Labscribber Workstation Toolkit", bg="#0f172a", fg="#475569", font=("Courier", 8))
        logo.pack(side=tk.BOTTOM, pady=10)

    def setup_plot_area(self):
        # Configure plotting canvas from matplotlib
        self.fig, self.ax = plt.subplots(figsize=(7, 5))
        self.fig.patch.set_facecolor('#0f172a')
        self.ax.set_facecolor('#1e293b')
        
        # Grid layout
        self.ax.grid(True, color='#334155', linestyle=':')
        self.ax.tick_params(colors='#94a3b8')
        for spine in self.ax.spines.values():
            spine.set_color('#475569')

        self.canvas = FigureCanvasTkAgg(self.fig, master=self.plot_panel)
        self.canvas_widget = self.canvas.get_tk_widget()
        self.canvas_widget.pack(fill=tk.BOTH, expand=True)

        self.toolbar = NavigationToolbar2Tk(self.canvas, self.plot_panel)
        self.toolbar.update()
        self.toolbar.pack(side=tk.BOTTOM, fill=tk.X)

    def update_plot(self):
        self.ax.clear()
        self.ax.grid(True, color='#334155', linestyle=':')
        self.ax.set_facecolor('#1e293b')
        self.fig.patch.set_facecolor('#0f172a')
        self.ax.tick_params(colors='#94a3b8')
        for spine in self.ax.spines.values():
            spine.set_color('#475569')
            
        # Set titles
        self.ax.set_title("${dataset.name} Spectrum", color='#f1f5f9', fontsize=12, fontweight='bold', pad=12)
        self.ax.set_xlabel("Wavelength / Shift / Energy", color='#94a3b8', fontsize=10)
        self.ax.set_ylabel("Intensity / Absorbance (a.u.)", color='#94a3b8', fontsize=10)

        # Plot original raw
        self.ax.plot(self.x_orig, self.y_orig, color='#64748b', linewidth=1.0, linestyle='--', label='Original Raw')
        
        # Plot processed
        self.ax.plot(self.x, self.y_processed, color='${dataset.color || '#0ea5e9'}', linewidth=1.8, label='Processed spectra')

        # Draw detected peaks
        for pk_x, pk_y in self.peaks:
            self.ax.plot(pk_x, pk_y, marker='v', color='#f43f5e', markersize=8)
            self.ax.annotate(f"{pk_x:.2f}", (pk_x, pk_y), textcoords="offset points", xytext=(0,10), ha='center', color='#f43f5e', fontsize=8, fontweight='bold')

        self.ax.legend(facecolor='#1e293b', edgecolor='#475569', labelcolor='#f1f5f9')
        self.canvas.draw()

    def load_csv(self):
        file_path = filedialog.askopenfilename(filetypes=[("CSV Data Files", "*.csv"), ("Text Files", "*.txt"), ("All Files", "*.*")])
        if not file_path:
            return
        
        try:
            # Parse CSV simple x,y pairs
            data = np.loadtxt(file_path, delimiter=',', skiprows=1, usecols=(0, 1))
            self.x_orig = data[:, 0]
            self.y_orig = data[:, 1]
            self.reset_data()
            messagebox.showinfo("Success", "Loaded dataset: " + str(len(self.x_orig)) + " points parsed.")
        except Exception as e:
            messagebox.showerror("Ingestion Error", f"Unable to parse file coordinates\\nEnsure rows are 'X,Y' paired values.\\nDetail: {e}")

    def apply_preprocessing(self):
        # 1. Start with raw
        temp_y = np.copy(self.y_orig)

        # 2. Smooth moving average if selected
        win = int(self.smooth_scale.get())
        if win > 1:
            # simple running moving window boxcar
            box = np.ones(win) / win
            # pad ends
            temp_y = np.convolve(temp_y, box, mode='same')

        # 3. Normalization
        if self.norm_var.get():
            y_min = np.min(temp_y)
            y_max = np.max(temp_y)
            if y_max != y_min:
                temp_y = (temp_y - y_min) / (y_max - y_min)

        self.y_processed = temp_y
        self.update_plot()

    def auto_pick_peaks(self):
        try:
            prominence = float(self.prom_entry.get())
        except ValueError:
            messagebox.showerror("Input Error", "Please provide a valid threshold prominence value (float).")
            return

        self.peaks = []
        # Find local peaks on processed array
        y = self.y_processed
        len_y = len(y)
        
        for i in range(2, len_y - 2):
            if y[i] > y[i-1] and y[i] > y[i-2] and y[i] > y[i+1] and y[i] > y[i+2]:
                base = min(y[i-2], y[i+2])
                if (y[i] - base) >= prominence and y[i] > 0.01:
                    self.peaks.append((self.x[i], y[i]))

        self.update_plot()
        messagebox.showinfo("Peaks Detected", f"Spotted {len(self.peaks)} unique peak coordinate indices.")

    def reset_data(self):
        self.x = np.copy(self.x_orig)
        self.y_processed = np.copy(self.y_orig)
        self.peaks = []
        self.norm_var.set(False)
        self.smooth_scale.set(11)
        self.update_plot()

if __name__ == "__main__":
    root = tk.Tk()
    app = LabscriberGUI(root)
    root.mainloop()
`;
}
